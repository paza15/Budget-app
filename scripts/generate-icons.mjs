// Renders the app's icon files into public/ (docs/DESIGN.md §15, docs/SPEC.md §7). Run it with
// `npm run icons` after changing docs/design/app-icon.svg, app-icon-maskable.svg, mark.svg or the
// --ink token, and commit the output: the build only copies public/.
//
// - From app-icon.svg (the On switch on a bone tile): apple-touch-icon.png (180), pwa-192.png,
//   pwa-512.png and favicon-32.png.
// - From app-icon-maskable.svg: pwa-maskable-512.png. It is the same artwork with the switch scaled
//   by 0.99253 and recentred, so the switch and its brass frame stay inside the maskable safe zone
//   (a circle of 40% of the width); only the soft shadows reach past it.
// - Every PNG is opaque, because iOS shows transparent pixels of a Home Screen icon as black: it is
//   flattened onto the solid base <rect> of its own SVG.
// - From mark.svg: favicon.svg in --ink, with a prefers-color-scheme style for the dark --ink.

import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const repo = new URL('../', import.meta.url)
const fromRepo = (path) => new URL(path, repo)

/** Each PNG is drawn at this multiple of its size, then scaled down: the engraved hairlines stay crisp. */
const SUPERSAMPLE = 4

const APP_ICON = 'docs/design/app-icon.svg'
const MASKABLE_ICON = 'docs/design/app-icon-maskable.svg'

const PNG_ICONS = [
  { file: 'apple-touch-icon.png', size: 180, source: APP_ICON },
  { file: 'pwa-192.png', size: 192, source: APP_ICON },
  { file: 'pwa-512.png', size: 512, source: APP_ICON },
  { file: 'pwa-maskable-512.png', size: 512, source: MASKABLE_ICON },
  { file: 'favicon-32.png', size: 32, source: APP_ICON },
]

const mark = await readFile(fromRepo('docs/design/mark.svg'), 'utf8')
const tokens = await readFile(fromRepo('src/styles/tokens.css'), 'utf8')

await mkdir(fromRepo('public/'), { recursive: true })

// Each source SVG with the hex fill of its full-size base <rect>: flattening onto it keeps every
// icon opaque even if the artwork ever gains a transparent edge.
const artwork = new Map()
for (const source of new Set(PNG_ICONS.map((icon) => icon.source))) {
  const svg = await readFile(fromRepo(source))
  const field = /<rect\b[^>]*\bwidth="1024"[^>]*\bfill="(#[0-9A-Fa-f]{6})"/.exec(svg.toString('utf8'))?.[1]
  if (!field) throw new Error(`${source} has no full-size background <rect> with a hex fill.`)
  artwork.set(source, { svg, field })
}

for (const { file, size, source } of PNG_ICONS) {
  const { svg, field } = artwork.get(source)
  const drawn = await sharp(svg, { density: (72 * size * SUPERSAMPLE) / 1024 })
    .flatten({ background: field })
    .removeAlpha()
    .toBuffer()
  // A 256-colour palette with dithering looks the same as true colour here at half the bytes,
  // which keeps the service worker's precache small.
  const png = await sharp(drawn)
    .resize(size, size, { kernel: 'lanczos3' })
    .png({ palette: true, quality: 100, dither: 1, compressionLevel: 9 })
    .toBuffer()
  const meta = await sharp(png).metadata()
  if (meta.width !== size || meta.height !== size || meta.hasAlpha) {
    throw new Error(`${file}: expected an opaque ${size}×${size} PNG.`)
  }
  await writeFile(fromRepo(`public/${file}`), png)
}

// favicon.svg: the monochrome mark (fill="currentColor") in the light --ink, switching to the dark
// --ink with the system appearance. A style rule outranks the fill attribute.
const inkLight = /:root\s*\{[^}]*?--ink:\s*(#[0-9A-Fa-f]{6})\s*;/.exec(tokens)?.[1]
const inkDark = /:root\[data-theme="dark"\]\s*\{[^}]*?--ink:\s*(#[0-9A-Fa-f]{6})\s*;/.exec(tokens)?.[1]
if (!inkLight || !inkDark) throw new Error('src/styles/tokens.css: could not read the light and dark --ink.')
if (!/<svg\b[^>]*\bfill="currentColor"/.test(mark)) {
  throw new Error('docs/design/mark.svg: expected fill="currentColor" on the <svg> element.')
}
const favicon = mark
  .replace(/<title>[\s\S]*?<\/title>\s*/, '')
  .replace(/(<svg\b[^>]*?)\bfill="currentColor"([^>]*>)/, `$1fill="${inkLight}"$2`)
  .replace(
    /(<svg\b[^>]*>)/,
    `$1\n<!-- Generated by scripts/generate-icons.mjs from docs/design/mark.svg. -->\n` +
      `<style>@media (prefers-color-scheme: dark) { svg { fill: ${inkDark}; } }</style>`,
  )
await writeFile(fromRepo('public/favicon.svg'), favicon)

for (const file of [...PNG_ICONS.map((icon) => icon.file), 'favicon.svg']) {
  const { size } = await stat(fromRepo(`public/${file}`))
  process.stdout.write(`public/${file.padEnd(22)} ${(size / 1024).toFixed(1).padStart(6)} KB\n`)
}
